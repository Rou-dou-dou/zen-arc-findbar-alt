// Registers the find bar as a Zen mod in a Zen profile (macOS, run by install.sh).
// Usage: osascript -l JavaScript install-mod.js <profile-dir> <repo-dir>
//
// Does what Zen does when it installs a mod from its store:
//  - adds/updates the entry in <profile>/zen-themes.json
//  - puts chrome.css and readme.md into <profile>/chrome/zen-themes/<id>/
//  - rebuilds <profile>/chrome/zen-themes.css from all enabled mods
// It also removes the older userChrome.css install of this find bar, if present.

ObjC.import("Foundation");
const fm = $.NSFileManager.defaultManager;

function exists(path) {
  return fm.fileExistsAtPath(path);
}
function read(path) {
  const s = $.NSString.stringWithContentsOfFileEncodingError(path, $.NSUTF8StringEncoding, null);
  return s.isNil() ? null : ObjC.unwrap(s);
}
function write(path, text) {
  const ok = $(text).writeToFileAtomicallyEncodingError(path, true, $.NSUTF8StringEncoding, null);
  if (!ok) throw new Error("Could not write " + path);
}
function mkdirs(path) {
  fm.createDirectoryAtPathWithIntermediateDirectoriesAttributesError(path, true, $(), null);
}
function join(...parts) {
  return parts.join("/").replace(/\/+/g, "/");
}

function run(argv) {
  const [profile, repo] = argv;
  const meta = JSON.parse(read(join(repo, "theme.json")));
  const css = read(join(repo, "chrome.css"));
  const readme = read(join(repo, "README.md")) || "";
  if (!meta || !css) throw new Error("theme.json or chrome.css missing in " + repo);

  // 1. Mod list
  const listPath = join(profile, "zen-themes.json");
  let mods = {};
  if (exists(listPath)) {
    try {
      mods = JSON.parse(read(listPath)) || {};
    } catch (e) {
      throw new Error("zen-themes.json is not valid JSON, nothing changed: " + e.message);
    }
  }
  const previous = mods[meta.id];
  mods[meta.id] = Object.assign({}, meta, {
    enabled: previous && previous.enabled === false ? false : true,
  });

  // 2. Mod files
  const modsRoot = join(profile, "chrome", "zen-themes");
  const modDir = join(modsRoot, meta.id);
  mkdirs(modDir);
  write(join(modDir, "chrome.css"), css);
  write(join(modDir, "readme.md"), readme);
  write(listPath, JSON.stringify(mods));

  // 3. Rebuild the combined stylesheet the same way Zen does
  const date = new Intl.DateTimeFormat("en-US", { dateStyle: "full", timeStyle: "full" }).format(new Date());
  let out =
    "/* Zen Mods - Generated by ZenMods.\n* FILE GENERATED AT: " + date + "\n" +
    "* DO NOT EDIT THIS FILE DIRECTLY!\n* Your changes will be overwritten.\n" +
    "* Instead, go to the preferences and edit the mods there.\n*/\n";
  for (const mod of Object.values(mods)) {
    if (!mod || mod.enabled === false) continue;
    const modCss = read(join(modsRoot, mod.id, "chrome.css"));
    if (modCss === null) continue;
    out += "\n/* Name: " + mod.name + " */\n";
    out += "/* Description: " + mod.description + " */\n";
    out += "/* Author: @" + mod.author + " */\n";
    out += modCss;
  }
  out += "\n/* End of Zen Mods */\n";
  write(join(profile, "chrome", "zen-themes.css"), out);

  // 4. Remove the older userChrome.css install of this find bar
  const ucPath = join(profile, "chrome", "userChrome.css");
  const uc = exists(ucPath) ? read(ucPath) : null;
  if (uc !== null && uc.includes("arc-findbar.css")) {
    write(ucPath, uc.split("\n").filter(l => !l.includes("arc-findbar.css")).join("\n"));
  }
  const oldCss = join(profile, "chrome", "arc-findbar.css");
  if (exists(oldCss)) fm.removeItemAtPathError(oldCss, null);

  return "Installed " + meta.name + " " + meta.version + " as a Zen mod.";
}
